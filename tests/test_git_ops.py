def test_remote_url_display_never_contains_credentials(
    git_repo: Path,
) -> None:
    run_git(
        git_repo,
        "remote",
        "add",
        "origin",
        "https://secret-token@github.com/acme/repo.git",
    )
    repo = GitRepo(git_repo)
    assert repo.remote_url() == "https://github.com/acme/repo.git"


def test_push_to_local_bare_remote(git_repo: Path, tmp_path: Path) -> None:
    bare = tmp_path / "origin.git"
    run_git(tmp_path, "init", "--bare", str(bare))
    run_git(git_repo, "remote", "add", "origin", str(bare))
    repo = GitRepo(git_repo)
    info = repo.create_worktree(
        title="Push test", issue=8, worktree_root=tmp_path / "worktrees"
    )
    (info.path / "app.py").write_text("pushed\n")
    repo.commit_changes(info, ["app.py"], subject="Push test", body="")
    pushed = repo.push(info)
    assert pushed.branch == info.branch
    branches = run_git(bare, "branch", "--list").stdout
    assert info.branch in branches
    assert repo.current_branch() == "main"
