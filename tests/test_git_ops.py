from __future__ import annotations

from pathlib import Path

import pytest

from coding_agent.errors import GitError, SecretDetected
from coding_agent.git_ops import (
    GitRepo,
    make_branch_name,
    validate_branch_name,
)
from tests.conftest import run_git


def test_not_a_git_repository(tmp_path: Path) -> None:
    with pytest.raises(GitError, match="Not a valid Git working tree"):
        GitRepo(tmp_path)


def test_branch_name_validation() -> None:
    assert make_branch_name("Fix login bug", issue=963) == "agent/issue-963-fix-login-bug"
    assert make_branch_name("Task") == "agent/task-task"
    for bad in ["main", "master", "agent/../evil", "agent//x", "agent/X", "feature/x"]:
        with pytest.raises(GitError):
            validate_branch_name(bad)
    assert validate_branch_name("agent/issue-963-fix") == "agent/issue-963-fix"


def test_worktree_is_isolated_and_source_branch_unchanged(git_repo: Path, tmp_path: Path) -> None:
    repo = GitRepo(git_repo)
    source_head = repo.head()
    info = repo.create_worktree(
        title="Fix login bug", issue=963, worktree_root=tmp_path / "worktrees"
    )
    assert info.branch.startswith("agent/issue-963-")
    assert info.path != git_repo
    assert not info.path.is_relative_to(git_repo)
    assert repo.current_branch() == "main"
    assert repo.head() == source_head
    assert repo.dirty_files() == ()
    assert run_git(info.path, "branch", "--show-current").stdout.strip() == info.branch
    assert info.base_branch == "main"

    (info.path / "app.py").write_text("def add(a, b):\n    return a + b + 0\n")
    commit = repo.commit_changes(
        info, ["app.py"], subject="Fix login", body="Details", issue=963
    )
    assert commit.files == ("app.py",)
    assert repo.current_branch() == "main"
    assert repo.head() == source_head
    assert repo.dirty_files() == ()
    message = run_git(info.path, "log", "-1", "--format=%B").stdout
    assert "Refs #963" in message
    assert "Generated by ai-coding-agent" in message


def test_existing_branch_gets_unique_suffix(git_repo: Path, tmp_path: Path) -> None:
    repo = GitRepo(git_repo)
    first = repo.create_worktree(
        title="Fix", issue=7, worktree_root=tmp_path / "worktrees"
    )
    second = repo.create_worktree(
        title="Fix", issue=7, worktree_root=tmp_path / "worktrees"
    )
    assert first.branch == "agent/issue-7-fix"
    assert second.branch == "agent/issue-7-fix-2"


def test_dirty_source_is_reported_but_not_copied(git_repo: Path, tmp_path: Path) -> None:
    (git_repo / "app.py").write_text("def add(a, b):\n    return 999\n")
    repo = GitRepo(git_repo)
    info = repo.create_worktree(
        title="Fix", issue=1, worktree_root=tmp_path / "worktrees"
    )
    assert info.had_dirty_source
    assert "999" not in (info.path / "app.py").read_text()
    assert "return a + b" in (info.path / "app.py").read_text()
    assert run_git(git_repo, "status", "--porcelain").stdout.strip()


def test_worktree_inside_source_is_rejected(git_repo: Path) -> None:
    repo = GitRepo(git_repo)
    with pytest.raises(GitError, match="outside the source working tree"):
        repo.create_worktree(title="Fix", issue=1, worktree_root=git_repo / "worktrees")


def test_commit_refuses_protected_and_non_agent_branches(
    git_repo: Path, tmp_path: Path
) -> None:
    repo = GitRepo(git_repo)
    assert repo.is_protected("main")
    with pytest.raises(GitError, match="protected branch"):
        repo.assert_agent_branch("main")

    info = repo.create_worktree(
        title="Fix", issue=2, worktree_root=tmp_path / "worktrees"
    )
    run_git(info.path, "switch", "-c", "feature/not-agent")
    (info.path / "app.py").write_text("changed\n")
    with pytest.raises(GitError, match="Unsafe branch name|protected branch"):
        repo.commit_changes(info, ["app.py"], subject="Nope", body="")


def test_commit_stages_only_task_files(git_repo: Path, tmp_path: Path) -> None:
    repo = GitRepo(git_repo)
    info = repo.create_worktree(
        title="Fix", issue=3, worktree_root=tmp_path / "worktrees"
    )
    (info.path / "app.py").write_text("changed app\n")
    (info.path / "README.md").write_text("changed readme\n")
    commit = repo.commit_changes(info, ["app.py"], subject="Only app", body="")
    assert commit.files == ("app.py",)
    status = run_git(info.path, "status", "--porcelain").stdout
    assert "README.md" in status
    assert "app.py" not in status
    changed = run_git(
        info.path, "show", "--name-only", "--format=", "HEAD"
    ).stdout.splitlines()
    assert changed == ["app.py"]


def test_staging_uses_literal_pathspecs(git_repo: Path, tmp_path: Path) -> None:
    repo = GitRepo(git_repo)
    info = repo.create_worktree(
        title="Literal pathspec", issue=13, worktree_root=tmp_path / "worktrees"
    )
    (info.path / "src").mkdir()
    literal = info.path / "src" / "*.py"
    other = info.path / "src" / "other.py"
    literal.write_text("literal\n")
    other.write_text("other\n")
    commit = repo.commit_changes(
        info,
        ["src/*.py"],
        subject="Stage literal file only",
        body="",
    )
    assert commit.files == ("src/*.py",)
    changed = run_git(
        info.path, "show", "--name-only", "--format=", "HEAD"
    ).stdout.splitlines()
    assert changed == ["src/*.py"]
    assert "other.py" in run_git(info.path, "status", "--porcelain").stdout


def test_sensitive_file_and_secret_content_are_blocked(
    git_repo: Path, tmp_path: Path
) -> None:
    repo = GitRepo(git_repo)
    info = repo.create_worktree(
        title="Fix", issue=4, worktree_root=tmp_path / "worktrees"
    )
    (info.path / ".env").write_text("OPENAI_API_KEY=sk-not-real\n")
    with pytest.raises(SecretDetected, match="sensitive file"):
        repo.commit_changes(info, [".env"], subject="Bad", body="")

    (info.path / "config.py").write_text(
        'API_KEY = "sk-' + "a" * 48 + '"\n'
    )
    with pytest.raises(SecretDetected, match="(?i)potential secret"):
        repo.commit_changes(info, ["config.py"], subject="Bad", body="")
    status = run_git(info.path, "status", "--porcelain").stdout
    assert "config.py" in status
    staged = run_git(info.path, "diff", "--cached", "--name-only").stdout
    assert staged.strip() == ""


